func TestPreparedDocumentsPreserveShardBytes(t *testing.T) {
	docs := []Document{
		{Name: "unicode.h", Content: []byte("class Example { const char* text = \"你好😀\"; };\n")},
		{Name: "generated.go", Content: []byte("// Code generated by tool. DO NOT EDIT.\npackage generated\n")},
		{Name: "file.bin", Content: []byte("a\x00binary")},
		{Name: "small.h", Content: []byte("a")},
		{Name: "empty.h"},
		{Name: "large.txt", Content: bytes.Repeat([]byte("hello"), 100)},
		{Name: "large.keep", Content: bytes.Repeat([]byte("hello"), 100)},
		{Name: "explicit.h", Content: []byte("hello"), Language: "C"},
		{Name: "skipped.h", SkipReason: SkipReasonTooLarge},
		{Name: "many.txt", Content: []byte("abcdefghijklmnopqrstuvwxyz")},
	}
	makeBuilder := func() *Builder {
		b, err := NewBuilder(Options{IndexDir: t.TempDir(), Parallelism: 3, ShardMax: 100,
			SizeMax: 200, TrigramMax: 20, LargeFiles: []string{"*.keep"}, DisableCTags: true,
			RepositoryDescription: zoekt.Repository{Name: "repo"}})
		if err != nil {
			t.Fatal(err)
		}
		b.indexTime = time.Unix(100, 0)
		b.id = "prepared-equivalence"
		t.Cleanup(func() {
			if err := b.Abort(); err != nil {
				t.Error(err)
			}
		})
		return b
	}
	serial, parallel := makeBuilder(), makeBuilder()
	prepared := make([]PreparedDocument, len(docs))
	var wg sync.WaitGroup
	for i, doc := range docs {
		if err := serial.Add(doc); err != nil {
			t.Fatal(err)
		}
		wg.Add(1)
		go func(i int, doc Document) {
			defer wg.Done()
			var checker DocChecker
			prepared[i] = parallel.PrepareDocument(doc, &checker)
		}(i, doc)
	}
	wg.Wait()
	for _, doc := range prepared {
		if err := parallel.AddPrepared(doc); err != nil {
			t.Fatal(err)
		}
	}
	if err := serial.Finish(); err != nil {
		t.Fatal(err)
	}
	if err := parallel.Finish(); err != nil {
		t.Fatal(err)
	}
	left, right := serial.opts.FindAllShards(), parallel.opts.FindAllShards()
	if len(left) != len(right) || len(left) < 2 {
		t.Fatalf("shard counts: %d, %d", len(left), len(right))
	}
	for i := range left {
		a, err := os.ReadFile(left[i])
		if err != nil {
			t.Fatal(err)
		}
		b, err := os.ReadFile(right[i])
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(a, b) {
			t.Fatalf("shard %d differs after parallel preparation", i)
		}
	}
}

func TestAbortPreservesPublishedIndex(t *testing.T) {
	opts := Options{IndexDir: t.TempDir(), Parallelism: 3, ShardMax: 10, DisableCTags: true,
		RepositoryDescription: zoekt.Repository{Name: "repo"}}
	old, err := NewBuilder(opts)
	if err != nil {
		t.Fatal(err)
	}
	if err := old.AddFile("old.go", []byte("package old")); err != nil {
		t.Fatal(err)
	}
	if err := old.Finish(); err != nil {
		t.Fatal(err)
	}
	shards := old.opts.FindAllShards()
	before, err := os.ReadFile(shards[0])
	if err != nil {
		t.Fatal(err)
	}
	next, err := NewBuilder(opts)
	if err != nil {
		t.Fatal(err)
	}
	for i := 0; i < 20; i++ {
		if err := next.AddFile("new.go", []byte("package replacement")); err != nil {
			t.Fatal(err)
		}
	}
	if err := next.Abort(); err != nil {
		t.Fatal(err)
	}
	if err := next.Abort(); err != nil {
		t.Fatal(err)
	}
	if err := next.Finish(); err == nil {
		t.Fatal("Finish after Abort must not publish")
	}
	after, err := os.ReadFile(shards[0])
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(before, after) {
		t.Fatal("Abort changed published content")
	}
	entries, err := os.ReadDir(opts.IndexDir)
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) != 1 || entries[0].Name() != filepath.Base(shards[0]) {
		t.Fatalf("unexpected artifacts after Abort: %v", entries)
	}
}

func TestPreparedDocumentOwner(t *testing.T) {
	first := &Builder{opts: Options{SizeMax: 100, TrigramMax: 20000}}
	second := &Builder{}
	var checker DocChecker
	doc := first.PrepareDocument(Document{Name: "x.go", Content: []byte("package x")}, &checker)
	if err := second.AddPrepared(doc); err == nil {
		t.Fatal("accepted another builder's prepared document")
	}
}
